<?php
	require __DIR__ . '/support/Test.php';
	require __DIR__ . '/support/MemoryProvider.php';
	require __DIR__ . '/../src/Runtime/DynDNS.php';
	require __DIR__ . '/../src/Tlsa/Tlsa.php';
	require __DIR__ . '/../src/Cli/Arguments.php';
	require __DIR__ . '/../src/Dns/MailAudit.php';
	require __DIR__ . '/../tools/check-artifact.php';
	foreach(array('config.json', 'x/config.json', '.env', '.env.production', 'private.log', '.codex-sessions.tsv', 'key.pem', 'x/journal.json', '../outside') as $path) testAssert(dnsapiForbiddenArtifact($path), 'reject artifact ' . $path);
	foreach(array('examples/config.example.json', 'src/Runtime/Config.php', 'docs/certbot.md') as $path) testAssert(!dnsapiForbiddenArtifact($path), 'allow artifact ' . $path);
	$record = DNSAPIArguments::record('mail:AAAA=2001:db8::1234', 'set', ttl: 600);
	testAssert($record['value'] === '2001:db8::1234' && $record['ttl'] === 600, 'IPv6 stays intact');
	testAssert(DNSAPIArguments::record('@:TXT=v=spf1 include:example.test -all', 'create')['value'] === 'v=spf1 include:example.test -all', 'SPF colon stays intact');
	testAssert(DNSAPIArguments::record('mail:A=192.0.2.1:600', 'set')['ttl'] === 600, 'legacy TTL');
	testAssert(DNSAPIArguments::record('@:TXT', 'set', 'value:123')['value'] === 'value:123', 'explicit value is unambiguous');
	testReject(fn() => DNSAPIRecords::validate(array('name' => '@', 'type' => 'A', 'value' => 'not-an-ip')), 'RECORD_IP_INVALID');
	testReject(fn() => DNSAPIRecords::validate(array('name' => '_25._tcp.mail', 'type' => 'TLSA', 'value' => '3 1 1 aa')), 'RECORD_TLSA_INVALID');
	testReject(fn() => DNSAPIRecords::name('other.test.', 'example.test'), 'RECORD_OUTSIDE_ZONE');
	testReject(fn() => DNSAPIRecords::name(str_repeat('a', 64), 'example.test'), 'RECORD_NAME_INVALID');
	$api = new ProductMemoryProvider();
	$service = new DNSAPIRecords($api, 'example.test');
	$api->records = array(array('id' => 'broken', 'name' => '_acme-challenge', 'type' => 'TXT', 'records' => false));
	testReject(fn() => $service->plan('create', array('name' => '_acme-challenge', 'type' => 'TXT', 'value' => 'new')), 'PROVIDER_RECORD_INVALID');
	testAssert($api->writes === 0, 'malformed RRSet is never interpreted as absent inventory');
	$api->records = array();
	$first = array('name' => '_acme-challenge', 'type' => 'TXT', 'value' => 'first');
	$second = array_replace($first, array('value' => 'second'));
	$service->apply($service->plan('create', $first));
	$service->apply($service->plan('create', $second));
	testAssert(count($api->records) === 2, 'create preserves sibling values');
	$writeCount = $api->writes;
	$service->apply($service->plan('create', $second));
	testAssert($api->writes === $writeCount, 'already present value is a no-op for every provider');
	$id = (string)array_key_first($api->records);
	testReject(fn() => $service->plan('update', array('id' => $id, 'name' => 'elsewhere', 'type' => 'TXT', 'value' => 'new')), 'RECORD_SELECTOR_MISMATCH');
	testReject(fn() => $service->plan('delete', array('id' => $id, 'value' => 'second')), 'RECORD_SELECTOR_MISMATCH');
	testReject(fn() => $service->plan('create', $second, true), 'ARGUMENT_CONFLICT');
	testReject(fn() => $service->plan('set', $second + array('ttl' => 600)), 'RECORD_AMBIGUOUS');
	testReject(fn() => $service->plan('set', array_replace($first, array('value' => 'third'))), 'RECORD_AMBIGUOUS');
	$service->apply($service->plan('delete', $first));
	testAssert(array_column($api->records, 'value') === array('second'), 'delete removes only exact value');
	$plan = $service->plan('set', $first, true);
	$api->createRecord(record: array_replace($second, array('value' => 'concurrent')));
	testReject(fn() => $service->apply($plan), 'RECORD_PLAN_STALE');
	foreach(array('12345678', 'a1234567') as $providerID) {
		$idAPI = new ProductMemoryProvider();
		$idAPI->records = array($providerID => $first + array('id' => $providerID));
		$idService = new DNSAPIRecords($idAPI, 'example.test');
		testAssert($idService->snapshot()[0]['id'] === $providerID, 'inventory retains string identity for numeric and alphanumeric IDs');
		testReject(fn() => $idService->plan('update', array('id' => $providerID, 'name' => 'elsewhere', 'type' => 'TXT', 'value' => 'new')), 'RECORD_SELECTOR_MISMATCH');
	}
	$directory = sys_get_temp_dir() . '/dnsapi-product-' . bin2hex(random_bytes(8));
	mkdir($directory, 0700);
	try {
		$config = array('API' => array('Netcup' => array('endpointURL' => 'https://ccp.netcup.net/run/webservice/servers/endpoint.php?JSON', 'KundenNR' => 'fixture', 'APIKey' => 'fixture', 'APIPass' => 'fixture')), 'domains' => array());
		foreach(array('one.test', 'two.test') as $zone) $config['domains'][$zone] = array('API' => 'Netcup', 'zoneID' => $zone, 'dynDNS' => array('secret' => 'fixture-secret', 'allowed' => array('home')));
		dnsapiValidateConfig($config);
		$apis = array('one.test' => new ProductMemoryProvider(), 'two.test' => new ProductMemoryProvider());
		$GLOBALS['dnsapiProviderFactory'] = fn($class, $zone, $options) => $apis[$zone];
		$cache = $directory . '/cache.json';
		DNSAPIDynDNS::update($config, array(), '192.0.2.1', $cache);
		testAssert(!file_exists($cache), 'empty request never writes cache');
		$query = array('host' => 'home', 'domain' => 'one.test', 'secret' => 'fixture-secret', 'ip' => '192.0.2.1');
		testAssert(DNSAPIDynDNS::update($config, $query, '', $cache)['result'] === 'OK', 'authorized update');
		testAssert(DNSAPIDynDNS::update($config, $query, '', $cache)['result'] === 'CACHE', 'repeat uses cache');
		testAssert(DNSAPIDynDNS::update($config, array_replace($query, array('domain' => 'two.test')), '', $cache)['result'] === 'OK', 'same hostname in other zone is not cache hit');
		testAssert($apis['two.test']->writes === 1, 'second zone updated');
		$before = file_get_contents($cache);
		DNSAPIDynDNS::update($config, array(), '192.0.2.1', $cache);
		testAssert(file_get_contents($cache) === $before, 'empty request preserves cache');
		testReject(fn() => DNSAPIDynDNS::update($config, array_replace($query, array('secret' => 'wrong')), '', $cache), 'REFUSED');
		testReject(fn() => DNSAPIDynDNS::update($config, array_replace($query, array('ip' => array('bad'))), '', $cache), 'IP_INVALID');
		testAssert(DNSAPIDynDNS::update($config, array_replace($query, array('ip' => '2001:db8::1')), '', $cache)['type'] === 'AAAA', 'IPv6 uses AAAA and separate cache');
		file_put_contents($cache, '{broken');
		testReject(fn() => DNSAPIDynDNS::update($config, $query, '', $cache), 'JOURNAL_CORRUPT');
		testAssert(file_get_contents($cache) === '{broken', 'corrupt cache not silently reset');
		unset($GLOBALS['dnsapiProviderFactory']);
		testReject(fn() => DNSAPITLSA::hash($directory . '/missing.pem'), 'TLSA_CERTIFICATE_INVALID');
		file_put_contents($directory . '/broken.pem', 'not a certificate');
		testReject(fn() => DNSAPITLSA::hash($directory . '/broken.pem'), 'TLSA_CERTIFICATE_INVALID');
		$key = openssl_pkey_new(array('private_key_bits' => 2048));
		$csr = openssl_csr_new(array('commonName' => 'one.test'), $key);
		$cert = openssl_csr_sign($csr, null, $key, 1);
		openssl_x509_export($cert, $pem);
		file_put_contents($directory . '/cert.pem', $pem);
		$hash = DNSAPITLSA::hash($directory . '/cert.pem');
		testAssert(preg_match('/^[a-f0-9]{64}$/D', $hash) === 1 && $hash !== hash('sha256', ''), 'valid TLSA hash');
		$config['tlsa-records'] = array($directory => array('%' => array(25)));
		testAssert(count(DNSAPITLSA::targets($config, $directory, '*.one.test one.test')) === 1, 'wildcard is not a service host');
		file_put_contents($directory . '/config.json', json_encode($config));
		$env = array('DNSAPI_CONFIG_FILE' => $directory . '/config.json', 'DNSAPI_TEST_RECORDS' => $directory . '/records.json');
		$cli = fn($args, $file = 'dnsapi-interface.php', $extra = array()) => testProcess(array_merge(array(PHP_BINARY, '-d', 'auto_prepend_file=' . __DIR__ . '/product-fixture.php', __DIR__ . '/../' . $file), $args), $extra + $env);
		testAssert($cli(array('--config-check'))['exit'] === 0, 'config check works offline');
		testAssert(!file_exists($directory . '/records.json'), 'config check has no provider mutations');
		$result = $cli(array('-x', 'one.test', '--action=set', '--name=home', '--type=AAAA', '--value=2001:db8::1', '--ttl=600', '--dry-run'));
		testAssert($result['exit'] === 0 && json_decode($result['output'], true)['dry_run'], 'CLI structured dry run: ' . $result['error']);
		testAssert(!file_exists($directory . '/records.json'), 'dry run does not write');
		$result = $cli(array('-x', 'one.test', '--set=home:A=192.0.2.2', '--dryrun'));
		testAssert($result['exit'] === 1 && str_contains($result['error'], 'ARGUMENT_UNKNOWN') && !file_exists($directory . '/records.json'), 'misspelled dry-run cannot trigger writes');
		testAssert($cli(array('-x', 'one.test', '--set=home:A=192.0.2.2:600'))['exit'] === 0, 'long set option executes');
		$result = $cli(array('-x', 'one.test', '--print=A', '--json'));
		testAssert($result['exit'] === 0 && count(json_decode($result['output'], true)) === 1, 'long print filter works');
		testAssert($cli(array('-x', 'one.test', '-s', 'broken'))['exit'] === 1, 'bad syntax exits nonzero');
		$result = $cli(array('--lineage=' . $directory, '--domains=one.test', '--certificate=' . $directory . '/missing.pem'), 'certbot-tlsa-generator.php');
		testAssert($result['exit'] === 1 && str_contains($result['error'], 'TLSA_CERTIFICATE_INVALID'), 'TLSA subprocess fails before writes');
		$result = $cli(array('--lineage=' . $directory, '--domains=one.test'), 'certbot-tlsa-generator.php');
		testAssert($result['exit'] === 0, 'TLSA publish works: ' . $result['error']);
		$records = json_decode(file_get_contents($directory . '/records.json'), true);
		testAssert(count($records) === 2, 'TLSA preserves unrelated A record');
		$result = $cli(array('--lineage=' . $directory, '--domains=one.test', '--mode=retire', '--old-value=3 1 1 ' . $hash, '--confirm-rollover-complete'), 'certbot-tlsa-generator.php');
		testAssert($result['exit'] === 1 && str_contains($result['error'], 'TLSA_RETIRE_VALUE_INVALID'), 'cannot retire current key');
		$old = '3 1 1 ' . str_repeat('a', 64);
		$records['old'] = array('id' => 'old', 'name' => '_25._tcp.one.test.', 'type' => 'TLSA', 'value' => $old);
		file_put_contents($directory . '/records.json', json_encode($records));
		$result = $cli(array('--lineage=' . $directory, '--domains=one.test'), 'certbot-tlsa-generator.php');
		testAssert($result['exit'] === 0 && count(json_decode(file_get_contents($directory . '/records.json'), true)) === 3, 'repeated publish preserves old rollover key');
		$result = $cli(array('--lineage=' . $directory, '--domains=one.test', '--mode=retire', '--old-value=' . $old), 'certbot-tlsa-generator.php');
		testAssert($result['exit'] === 1 && str_contains($result['error'], 'TLSA_ROLLOVER_CONFIRMATION_REQUIRED'), 'retirement requires operational confirmation');
		$result = $cli(array('--lineage=' . $directory, '--domains=one.test', '--mode=retire', '--old-value=' . $old, '--confirm-rollover-complete'), 'certbot-tlsa-generator.php');
		testAssert($result['exit'] === 0 && count(json_decode(file_get_contents($directory . '/records.json'), true)) === 2, 'retirement removes exact old key and preserves active key');
	} finally {
		foreach(glob($directory . '/*') as $path) unlink($path);
		rmdir($directory);
	}
	$dns = new DNSAPIDNS(dnsapiSettings(array()), new DNSAPIDeadline(10), fn() => array('output' => ';; ->>HEADER<<- opcode: QUERY, status: NXDOMAIN, id: 1', 'exit' => 0, 'duration_ms' => 1));
	$audit = (new DNSAPIMailAudit($dns, '192.0.2.53'))->check('example.test');
	testAssert($audit['checks']['SPF']['status'] === 'attention' && $audit['checks']['DKIM']['status'] === 'skipped' && $audit['checks']['DNSSEC']['status'] === 'unconfirmed', 'audit does not claim missing/unverified checks passed');
	echo "OK: $testCount product checks on PHP " . PHP_VERSION . PHP_EOL;
