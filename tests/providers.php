<?php
	require __DIR__ . '/support/Test.php';
	require __DIR__ . '/../src/Provider/Netcup.php';
	require __DIR__ . '/../src/Provider/HetznerCloud.php';
	require __DIR__ . '/../src/Dns/Records.php';
	require __DIR__ . '/../src/Certbot/Helpers.php';
	$directory = sys_get_temp_dir() . '/dnsapi-wire-' . bin2hex(random_bytes(8));
	mkdir($directory, 0700);
	$statePath = $directory . '/state.json';
	$seed = array('requests' => array(), 'next' => 100, 'netcup' => array('42' => array('id' => '42', 'hostname' => 'mail', 'type' => 'A', 'destination' => '192.0.2.1', 'priority' => 0, 'state' => 'yes')), 'cloud' => array('@/A' => array('id' => '@/A', 'name' => '@', 'type' => 'A', 'ttl' => 300, 'records' => array(array('value' => '192.0.2.1'))), '_acme-challenge/TXT' => array('id' => '_acme-challenge/TXT', 'name' => '_acme-challenge', 'type' => 'TXT', 'ttl' => 300, 'records' => array(array('value' => '"foreign"')))));
	file_put_contents($statePath, json_encode($seed));
	$socket = stream_socket_server('tcp://127.0.0.1:0', $errno, $error);
	$address = stream_socket_get_name($socket, false); fclose($socket);
	$server = proc_open(array(PHP_BINARY, '-S', $address, __DIR__ . '/provider-router.php'), array(0 => array('file', '/dev/null', 'r'), 1 => array('file', '/dev/null', 'w'), 2 => array('file', '/dev/null', 'w')), $pipes, null, array('PATH' => getenv('PATH'), 'DNSAPI_HTTP_STATE' => $statePath));
	try {
		$health = curl_init('http://' . $address . '/health');
		curl_setopt_array($health, array(CURLOPT_RETURNTRANSFER => true, CURLOPT_TIMEOUT_MS => 100));
		$ready = false;
		for($i = 0; $i < 100; $i++) { if(curl_exec($health) === 'ready') { $ready = true; break; } usleep(10000); }
		testAssert($ready, 'loopback HTTP fixture starts');
		$netcup = new netcupAPI('example.test', array('endpointURL' => 'http://' . $address . '/netcup', 'KundenNR' => 'fixture', 'APIKey' => 'fixture', 'APIPass' => 'fixture'));
		testAssert(is_array($netcup->setRecord(name: 'mail', type: 'A', value: '192.0.2.2')), 'Netcup value update succeeds');
		$state = json_decode(file_get_contents($statePath), true);
		$updates = array_values(array_filter($state['requests'], fn($r) => ($r['body']['action'] ?? '') === 'updateDnsRecords'));
		testAssert($updates[0]['body']['param']['dnsrecordset']['dnsrecords'][0]['id'] === '42', 'actual wire update carries existing ID');
		testAssert(count($state['netcup']) === 1 && $state['netcup']['42']['destination'] === '192.0.2.2', 'update does not append old address');
		testAssert($netcup->multiSetRecords(array(array('name' => 'mail', 'type' => 'A', 'value' => '192.0.2.3'))) !== false, 'bulk replacement succeeds');
		$state = json_decode(file_get_contents($statePath), true);
		testAssert(count($state['netcup']) === 1 && $state['netcup']['42']['destination'] === '192.0.2.3', 'bulk update keeps ID');
		$netcup->createRecord(name: '_acme-challenge', type: 'TXT', value: 'first');
		$netcup->createRecord(name: '_acme-challenge', type: 'TXT', value: 'second');
		testAssert(count($netcup->getRecords()) === 3, 'create adds sibling challenge');
		$before = json_decode(file_get_contents($statePath), true);
		testAssert($netcup->setRecord(name: '_acme-challenge', type: 'TXT', value: 'ambiguous') === false, 'ambiguous Netcup set rejected');
		$state = json_decode(file_get_contents($statePath), true);
		testAssert($state['netcup'] === $before['netcup'], 'ambiguous set has no mutation');
		$netcup->deleteRecord(name: '_acme-challenge', type: 'TXT', value: 'first');
		testAssert(count($netcup->getRecords()) === 2, 'Netcup exact deletion preserves foreign record');
		$netcup->createRecord(name: '@', type: 'MX', value: '0 mail.example.test.');
		$mx = $netcup->createRecord(name: '@', type: 'MX', value: '20 mail.example.test.');
		testAssert($mx['value'] === '20 mail.example.test.' && count($netcup->getRecords()) === 4, 'MX priority participates in record identity');
		testAssert($netcup->createRecord(record: $mx)['id'] === $mx['id'], 'Netcup compatibility MX record round-trips without duplicated priority');
		testAssert($netcup->deleteRecord(name: '@', type: 'MX', value: '0 mail.example.test.'), 'Netcup exact MX deletion parses priority and destination');
		$rawMX = $netcup->getRecords()[$mx['id']];
		testAssert($netcup->deleteRecord(record: $rawMX), 'Netcup raw MX inventory record is an exact deletion selector');
		$netcupService = new DNSAPIRecords($netcup, 'example.test');
		$ttlPlan = $netcupService->plan('set', array('name' => 'mail', 'type' => 'A', 'value' => '192.0.2.4', 'ttl' => 600));
		testAssert($ttlPlan['warnings'] === array('NETCUP_ZONE_TTL_UNCHANGED'), 'Netcup explicitly reports zone TTL limitation');
		$netcupService->apply($ttlPlan);
		$state = json_decode(file_get_contents($statePath), true);
		$updates = array_values(array_filter($state['requests'], fn($r) => ($r['body']['action'] ?? '') === 'updateDnsRecords'));
		testAssert(!isset(end($updates)['body']['param']['dnsrecordset']['dnsrecords'][0]['ttl']), 'Netcup never sends unsupported per-record TTL');
		testAssert(!$netcup->deleteRecord(id: '42', value: '192.0.2.99') && $netcup->lastError === 'RECORD_SELECTOR_MISMATCH', 'Netcup mismatched value cannot delete by ID');
		$state['ignore_delete'] = true; file_put_contents($statePath, json_encode($state));
		testAssert(!$netcup->deleteRecord(id: '42', value: '192.0.2.4') && $netcup->lastError === 'PROVIDER_CHANGE_UNCONFIRMED', 'Netcup success status does not prove deletion');
		$state = json_decode(file_get_contents($statePath), true);
		unset($state['ignore_delete']); $state['after_write_error'] = true; file_put_contents($statePath, json_encode($state));
		testReject(fn() => $netcupService->apply($netcupService->plan('set', array('name' => 'mail', 'type' => 'A', 'value' => '192.0.2.5'))), 'PROVIDER_RESPONSE_INVALID');
		$state = json_decode(file_get_contents($statePath), true);
		testAssert($state['netcup']['42']['destination'] === '192.0.2.5', 'failed response can follow a real mutation; no blind rollback or retry');
		unset($state['after_write_error']); file_put_contents($statePath, json_encode($state));
		testAssert($netcup->getRecords()['42']['destination'] === '192.0.2.5', 'inventory reconciles uncertain write');
		$state = json_decode(file_get_contents($statePath), true);
		$state['invalid_netcup_record'] = true; file_put_contents($statePath, json_encode($state));
		testReject(fn() => $netcup->getRecords(), 'PROVIDER_RECORD_INVALID');
		unset($state['invalid_netcup_record']); file_put_contents($statePath, json_encode($state));
		unset($netcupService, $netcup);
		$state = json_decode(file_get_contents($statePath), true);
		$last = end($state['requests']);
		testAssert($last['body']['action'] === 'logout' && $last['body']['param']['apisessionid'] === 'fixture-session' && !isset($last['body']['param']['apipassword']), 'logout sends session not password');
		$cloud = new hetznerCloudAPI('1', array('recordsURL' => 'http://' . $address . '/zones', 'APIToken' => 'fixture', 'zoneName' => 'example.test'));
		testAssert(count($cloud->getRecords()) === 2, 'Cloud pagination consumes all pages');
		$ttl = dnsapiChallengeTTL($cloud->getRecords(), 'example.test', 'example.test');
		testAssert($ttl === 300 && is_array($cloud->createRecord(name: '_acme-challenge', type: 'TXT', value: 'ttl-token', ttl: $ttl)), 'Cloud append uses existing RRSet TTL');
		testAssert($cloud->getRecords()['_acme-challenge/TXT']['ttl'] === 300 && $cloud->deleteRecord(name: '_acme-challenge', type: 'TXT', value: 'ttl-token'), 'Cloud TTL is not changed by temporary challenge');
		$state = json_decode(file_get_contents($statePath), true);
		$state['cloud']['_acme-challenge/TXT']['ttl'] = null; file_put_contents($statePath, json_encode($state));
		$ttl = dnsapiChallengeTTL($cloud->getRecords(), 'example.test', 'example.test');
		testAssert($ttl === null && is_array($cloud->createRecord(name: '_acme-challenge', type: 'TXT', value: 'inherited-token', ttl: $ttl)), 'Cloud inherited zone TTL remains inherited');
		testAssert($cloud->getRecords()['_acme-challenge/TXT']['ttl'] === null && $cloud->deleteRecord(name: '_acme-challenge', type: 'TXT', value: 'inherited-token'), 'inherited TTL survives cleanup');
		$result = $cloud->createRecord(name: '_acme-challenge.example.test.', type: 'TXT', value: 'new');
		testAssert(is_array($result), 'Cloud async append succeeds');
		$state = json_decode(file_get_contents($statePath), true);
		testAssert($state['polls'] === 2, 'Cloud waits for action completion');
		testAssert(array_column($state['cloud']['_acme-challenge/TXT']['records'], 'value') === array('"foreign"', '"new"'), 'Cloud append preserves other values');
		testAssert($cloud->deleteRecord(name: '_acme-challenge', type: 'TXT', value: 'new'), 'Cloud remove exact value');
		$state = json_decode(file_get_contents($statePath), true);
		testAssert(array_column($state['cloud']['_acme-challenge/TXT']['records'], 'value') === array('"foreign"'), 'Cloud remove preserves foreign TXT');
		testAssert($cloud->multiSetRecords(array(array('name' => '_25._tcp.mail', 'type' => 'TLSA', 'value' => '3 1 1 ' . str_repeat('a', 64)))), 'Cloud creates missing TLSA RRSet');
		testAssert($cloud->multiSetRecords(array(array('name' => '_25._tcp.mail', 'type' => 'TLSA', 'value' => '3 1 1 ' . str_repeat('b', 64)))), 'Cloud replaces existing TLSA RRSet');
		testAssert($cloud->deleteRecord(name: '_25._tcp.mail', type: 'TLSA', value: '3 1 1 ' . str_repeat('b', 64)), 'Cloud removes final value');
		testAssert(!isset($cloud->getRecords()['_25._tcp.mail/TLSA']), 'empty RRSet disappears after final removal');
		$service = new DNSAPIRecords($cloud, 'example.test');
		$service->apply($service->plan('create', array('name' => '_acme-challenge', 'type' => 'TXT', 'value' => 'second')));
		$service->apply($service->plan('set', array('id' => '_acme-challenge/TXT', 'value' => 'foreign')));
		$state = json_decode(file_get_contents($statePath), true);
		testAssert(count($state['cloud']['_acme-challenge/TXT']['records']) === 2, 'Cloud ID with existing value cannot erase sibling through service');
		testReject(fn() => $service->plan('set', array('id' => '_acme-challenge/TXT', 'value' => 'third')), 'RECORD_AMBIGUOUS');
		foreach(array('missing_pagination' => 'PROVIDER_PAGINATION_INVALID', 'incomplete_rrset' => 'PROVIDER_RECORD_INVALID') as $flag => $code) {
			$state = json_decode(file_get_contents($statePath), true);
			$state[$flag] = true; file_put_contents($statePath, json_encode($state));
			testAssert($cloud->getRecords() === false && $cloud->lastError === $code, 'incomplete Cloud inventory is not successful absence: ' . $flag);
			unset($state[$flag]); file_put_contents($statePath, json_encode($state));
		}
		$state['ignore_add'] = true; file_put_contents($statePath, json_encode($state));
		testAssert($cloud->createRecord(name: '_acme-challenge', type: 'TXT', value: 'not-created') === false && $cloud->lastError === 'PROVIDER_CHANGE_UNCONFIRMED', 'successful Cloud action cannot fabricate missing record');
		$state = json_decode(file_get_contents($statePath), true); unset($state['ignore_add']);
		$state['pagination_cycle'] = true; file_put_contents($statePath, json_encode($state));
		testAssert($cloud->getRecords() === false && $cloud->lastError === 'PROVIDER_PAGINATION_INVALID', 'cyclic pagination fails closed');
		unset($state['pagination_cycle']); $state['malformed'] = true; file_put_contents($statePath, json_encode($state));
		testAssert($cloud->getRecords() === false, 'malformed JSON is not empty successful inventory');
		unset($state['malformed']); $state['action_stuck'] = true; file_put_contents($statePath, json_encode($state));
		$GLOBALS['dnsapiDeadline'] = new DNSAPIDeadline(0.1);
		testReject(fn() => $cloud->createRecord(name: '_acme-challenge', type: 'TXT', value: 'timeout'), 'PROPAGATION_TIMEOUT');
		unset($GLOBALS['dnsapiDeadline']);
		$state = json_decode(file_get_contents($statePath), true);
		testAssert(in_array('"timeout"', array_column($state['cloud']['_acme-challenge/TXT']['records'], 'value'), true), 'action timeout retains already-created record for reconciliation');
		$state['failure'] = true; file_put_contents($statePath, json_encode($state));
		testAssert($cloud->getRecords() === false && !str_contains($cloud->lastError, 'private-fixture-value'), 'HTTP error is not empty inventory and body is not logged');
	} finally {
		unset($netcupService, $service, $netcup, $cloud, $health);
		proc_terminate($server); proc_close($server);
		foreach(glob($directory . '/*') as $path) unlink($path);
		rmdir($directory);
	}
	echo "OK: $testCount provider wire checks on PHP " . PHP_VERSION . PHP_EOL;
